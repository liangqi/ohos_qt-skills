#!/usr/bin/env python3
"""
kb-init.py — New contributor initialization for ohos_qt-skills.

Generates ENV.local.md, sets git user.name, validates environment.
Works for both team members and external contributors.

Usage: python _scripts/kb-init.py
"""

import os
import sys
import subprocess
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
ENV_LOCAL = REPO_ROOT / "ENV.local.md"
ENV_EXAMPLE = REPO_ROOT / "ENV.md"


def ask(prompt, default=""):
    """Ask user for input with optional default."""
    if default:
        result = input(f"{prompt} [{default}]: ").strip()
        return result if result else default
    return input(f"{prompt}: ").strip()


def run_cmd(cmd, cwd=None):
    """Run command, return (rc, stdout)."""
    try:
        r = subprocess.run(cmd, shell=True, cwd=cwd, capture_output=True, text=True, timeout=30)
        return r.returncode, r.stdout.strip()
    except Exception:
        return -1, ""


def main():
    print("=" * 50)
    print("  ohos_qt-skills — Contributor Initialization")
    print("=" * 50)
    print()

    # Step 1: Identity
    print("Step 1/4: Identity")
    print("-" * 30)

    # Try to get from git config
    rc, git_name = run_cmd("git config user.name", cwd=str(REPO_ROOT))
    default_name = git_name if rc == 0 and git_name else ""

    my_name = ask("  Your name/slug (for branch naming & contributors field)", default_name)
    if not my_name:
        print("  ERROR: name is required.")
        sys.exit(1)

    # Sanitize slug
    my_name_slug = my_name.lower().replace(" ", "-").replace("_", "-")
    for c in my_name_slug:
        if not (c.isalnum() or c == "-"):
            my_name_slug = my_name_slug.replace(c, "")

    print(f"  -> MY_NAME = {my_name_slug}")

    # Set git user.name if not set
    if not default_name:
        run_cmd(f'git config user.name "{my_name}"', cwd=str(REPO_ROOT))
        print(f"  -> Set git user.name = {my_name}")

    print()

    # Step 2: Environment paths
    print("Step 2/4: Environment Paths (optional, press Enter to skip)")
    print("-" * 30)

    qt5_12_src = ask("  Qt 5.12 source path (QT5_12_SRC)", "")
    qt5_15_src = ask("  Qt 5.15 source path (QT5_15_SRC)", "")
    ohos_sdk = ask("  HarmonyOS SDK path (OHOS_SDK_ROOT)", "")

    print()

    # Step 3: Generate ENV.local.md
    print("Step 3/4: Generate ENV.local.md")
    print("-" * 30)

    env_content = f"""# ENV.local.md — Personal environment configuration
# Generated by kb-init.py
# This file is gitignored. Do NOT commit it.

MY_NAME={my_name_slug}
GIT_USERNAME={my_name}

# Qt source paths (fill if available)
QT5_12_SRC={qt5_12_src}
QT5_15_SRC={qt5_15_src}

# HarmonyOS SDK
OHOS_SDK_ROOT={ohos_sdk}
"""

    ENV_LOCAL.write_text(env_content, encoding="utf-8")
    print(f"  -> Written: {ENV_LOCAL}")

    print()

    # Step 4: Validate environment
    print("Step 4/4: Environment Check")
    print("-" * 30)

    checks = []

    # Git
    rc, ver = run_cmd("git --version")
    checks.append(("git", rc == 0, ver))

    # Bash >= 4
    rc, ver = run_cmd("bash -c 'echo $BASH_VERSION'")
    bash_ok = rc == 0 and ver and int(ver.split(".")[0]) >= 4
    checks.append(("bash>=4", bash_ok, ver))

    # Python
    checks.append(("python", True, f"{sys.version_info.major}.{sys.version_info.minor}"))

    # gitleaks (optional)
    rc, ver = run_cmd("gitleaks version")
    checks.append(("gitleaks (optional)", rc == 0, ver.split("\n")[0] if ver else "not found"))

    for name, ok, detail in checks:
        status = "OK" if ok else "MISSING"
        print(f"  [{status:7s}] {name}: {detail}")

    print()

    # Summary
    print("=" * 50)
    print("  Initialization complete!")
    print()
    print(f"  MY_NAME: {my_name_slug}")
    print(f"  ENV.local.md: {ENV_LOCAL}")
    print()
    print("  Next steps:")
    print("    1. Install pre-push hook:")
    print("       cp _scripts/pre-push .git/hooks/pre-push")
    print("    2. Read CONTRIBUTING.md for PR workflow")
    print("    3. Read _index/_task-routing.md to find relevant pages")
    print("=" * 50)


if __name__ == "__main__":
    main()
