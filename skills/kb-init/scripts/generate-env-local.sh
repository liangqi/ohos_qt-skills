#!/bin/bash
# generate-env-local.sh — deterministically generate ENV.local.md
#
# Usage: bash skills/kb-init/scripts/generate-env-local.sh [OPTIONS]
# Options:
#   --deveco-path=PATH         DevEco Studio path
#   --qt5-12-src=PATH          Qt 5.12 source path
#   --qt5-15-src=PATH          Qt 5.15 source path
#   --qt-build-root=PATH       Qt build output root directory
#   --qt5-12-ohos-sdk=PATH     Qt 5.12 OHOS SDK path
#   --qt5-15-ohos-sdk=PATH     Qt 5.15 OHOS SDK path
#   --ohos-sdk-native=PATH     OHOS SDK native path
# Output: writes ENV.local.md into the knowledge base root
# Exit codes: 0=success

set -uo pipefail

# Go up three levels from scripts/ to reach the KB root
KB_ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
OUTPUT="$KB_ROOT/ENV.local.md"

DEVECO_PATH=""
QT5_12_SRC=""
QT5_15_SRC=""
QT_BUILD_ROOT=""
QT5_12_OHOS_SDK=""
QT5_15_OHOS_SDK=""
OHOS_SDK_NATIVE=""
OHOS_TEMPLATE_SRC=""

for arg in "$@"; do
  case "$arg" in
    --deveco-path=*) DEVECO_PATH="${arg#*=}";;
    --qt5-12-src=*) QT5_12_SRC="${arg#*=}";;
    --qt5-15-src=*) QT5_15_SRC="${arg#*=}";;
    --qt-build-root=*) QT_BUILD_ROOT="${arg#*=}";;
    --qt5-12-ohos-sdk=*) QT5_12_OHOS_SDK="${arg#*=}";;
    --qt5-15-ohos-sdk=*) QT5_15_OHOS_SDK="${arg#*=}";;
    --ohos-sdk-native=*) OHOS_SDK_NATIVE="${arg#*=}";;
    --ohos-template-src=*) OHOS_TEMPLATE_SRC="${arg#*=}";;
    *) echo "Unknown option: $arg" >&2; exit 2;;
  esac
done

cat > "$OUTPUT" << HEADER
# ENV.local.md — local path configuration

> This file is generated by the \`skills/kb-init/\` initialization skill.
> Knowledge pages refer to paths by variable name; when the agent reads them, the values in this file override the defaults in \`ENV.md\`.
> This file is gitignored and never checked in.
>
> Generated: $(date +%F)

---

HEADER

# IDE and tool paths
echo "## IDE and tool paths" >> "$OUTPUT"
echo "" >> "$OUTPUT"
echo "| Variable | Your value |" >> "$OUTPUT"
echo "|----------|------------|" >> "$OUTPUT"
[ -n "$DEVECO_PATH" ] && echo "| \`DEVECO_PATH\` | \`$DEVECO_PATH\` |" >> "$OUTPUT"
[ -n "$OHOS_SDK_NATIVE" ] && echo "| \`OHOS_SDK_NATIVE\` | \`$OHOS_SDK_NATIVE\` |" >> "$OUTPUT"
echo "" >> "$OUTPUT"

# Qt source paths (if any)
if [ -n "$QT5_12_SRC" ] || [ -n "$QT5_15_SRC" ]; then
  echo "## Qt source paths" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
  echo "| Variable | Your value |" >> "$OUTPUT"
  echo "|----------|------------|" >> "$OUTPUT"
  [ -n "$QT5_12_SRC" ] && echo "| \`QT5_12_SRC\` | \`$QT5_12_SRC\` |" >> "$OUTPUT"
  [ -n "$QT5_15_SRC" ] && echo "| \`QT5_15_SRC\` | \`$QT5_15_SRC\` |" >> "$OUTPUT"
  echo "" >> "$OUTPUT"

  # Template path: explicit value > 5.15 source > 5.12 source
  _tpl_src=""
  if [ -n "$OHOS_TEMPLATE_SRC" ]; then
    _tpl_src="$OHOS_TEMPLATE_SRC"
  elif [ -n "$QT5_15_SRC" ]; then
    _tpl_src="$QT5_15_SRC/qtbase/src/harmonyos/templates"
  elif [ -n "$QT5_12_SRC" ]; then
    _tpl_src="$QT5_12_SRC/qtbase/src/harmonyos/templates"
  fi
  if [ -n "$_tpl_src" ]; then
    echo "## Templates" >> "$OUTPUT"
    echo "" >> "$OUTPUT"
    echo "| Variable | Your value |" >> "$OUTPUT"
    echo "|----------|------------|" >> "$OUTPUT"
    echo "| \`OHOS_TEMPLATE_SRC\` | \`$_tpl_src\` |" >> "$OUTPUT"
    echo "" >> "$OUTPUT"
  fi
fi

# Standalone template (when there's no source tree)
if [ -z "$QT5_12_SRC" ] && [ -z "$QT5_15_SRC" ] && [ -n "$OHOS_TEMPLATE_SRC" ]; then
  echo "## Templates" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
  echo "| Variable | Your value |" >> "$OUTPUT"
  echo "|----------|------------|" >> "$OUTPUT"
  echo "| \`OHOS_TEMPLATE_SRC\` | \`$OHOS_TEMPLATE_SRC\` |" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
fi

# Build artifacts and SDKs
echo "## Build artifacts and SDKs" >> "$OUTPUT"
echo "" >> "$OUTPUT"
echo "| Variable | Your value |" >> "$OUTPUT"
echo "|----------|------------|" >> "$OUTPUT"
[ -n "$QT_BUILD_ROOT" ] && echo "| \`QT_BUILD_ROOT\` | \`$QT_BUILD_ROOT\` |" >> "$OUTPUT"
[ -n "$QT5_12_OHOS_SDK" ] && echo "| \`QT5_12_OHOS_SDK\` | \`$QT5_12_OHOS_SDK\` |" >> "$OUTPUT"
[ -n "$QT5_15_OHOS_SDK" ] && echo "| \`QT5_15_OHOS_SDK\` | \`$QT5_15_OHOS_SDK\` |" >> "$OUTPUT"
echo "" >> "$OUTPUT"

echo "ENV.local.md generated: $OUTPUT"
