def env_of(state) -> Dict:
    return state.read_json("env.json", default={}) or {}


QT6_TOOLCHAIN_REL = os.path.join("lib", "cmake", "Qt6", "qt.toolchain.cmake")
DEPLOY_SETTINGS_GLOB = "**/*-harmony-deployment-settings.json"


def qt6_toolchain(qt_prefix) -> Optional[Path]:
    """`<kit>/lib/cmake/Qt6/qt.toolchain.cmake` -- the single entry point for Qt6 cross-compiling.

    A prebuilt kit is not an ordinary SDK that "just works given CMAKE_PREFIX_PATH": the compiler, sysroot
    and OPENSSL_* all live in the toolchain file. Given only the prefix, cmake builds with the host compiler a
    .so that runs on the CI machine and fails to dlopen on the device -- "it compiles" then means nothing at all.
    """
    if not qt_prefix:
        return None
    candidate = Path(str(qt_prefix)) / QT6_TOOLCHAIN_REL
    return candidate if candidate.is_file() else None


def mingw32_make(env: Dict) -> Optional[str]:
    """Location of mingw32-make.

    The Qt prebuilt kit ships `mingw_64/bin/mingw32-make.exe`, but it is not on PATH:
    looking only at PATH wrongly concludes "no make" and falls back to Ninja (which spins idle in restricted sessions).
    """
    if env.get("make_program"):
        return str(env["make_program"])
    found = shutil.which("mingw32-make")
    if found:
        return found
    host = env.get("qt_host_sdk")
    if host:
        for name in ("mingw32-make.exe", "mingw32-make", "make.exe"):
            candidate = Path(host) / "bin" / name
            if candidate.is_file():
                return str(candidate)
    return None


def pkgconfig_env(state, env: Dict) -> Dict[str, str]:
    """Make the project's `pkg_check_modules` work on this machine.

    Windows hosts have no pkg-config; the stand-in generated by `pkgconfig --write-shim` only counts
    if it is on PATH. The `.pc` files contain build-machine absolute paths, so
    `PKG_CONFIG_LIBDIR` must be set explicitly (pkgconf semantics: when set, only these directories are searched).
    """
    out: Dict[str, str] = {}
    root = Path(state.project_root)
    bin_dir = state.state_dir / "bin"
    if (bin_dir / "pkg-config").is_file() or (bin_dir / "pkg-config.bat").is_file():
        out["PATH"] = str(bin_dir) + os.pathsep + os.environ.get("PATH", "")
    libs = env.get("ohos_libs") or str(root / "ohos-libs")
    try:
        from . import pkgconfig
        dirs = [str(d) for d in pkgconfig.search_dirs(Path(libs)) if d.is_dir()]
    except Exception:
        dirs = []
    if dirs:
        out["PKG_CONFIG_LIBDIR"] = os.pathsep.join(dirs)
    return out


def default_generator(env: Dict) -> str:
    """On Windows NMake and Ninja each have their own pitfalls; MinGW Makefiles is the most stable for CLI use."""
    if env.get("generator"):
        return str(env["generator"])
    if os.name == "nt":
        if mingw32_make(env):
            return "MinGW Makefiles"
        return "Ninja" if shutil.which("ninja") else "NMake Makefiles"
    return "Ninja" if shutil.which("ninja") else "Unix Makefiles"


def qt6_configure_problems(env: Dict) -> list:
    """Which items the Qt6 kit is missing; missing items make cmake spew unrelated errors, so say it plainly here first."""
    problems = []
    host = env.get("qt_host_sdk")
    if not host:
        problems.append("qt_host_sdk is not configured (host kit, QT_HOST_PATH; cross-compiling needs it for moc/rcc)")
    elif not (Path(host) / "bin").is_dir():
        problems.append("qt_host_sdk=%s does not exist or has no bin/" % host)
    native = env.get("ohos_sdk_native")
    if not native:
        problems.append("ohos_sdk_native is not configured (<OHOS SDK>/native)")
    elif not (Path(native) / "build" / "cmake" / "ohos.toolchain.cmake").is_file():
        problems.append("ohos_sdk_native=%s has no build/cmake/ohos.toolchain.cmake"
                        % native)
    return problems


def qt6_configure_args(env: Dict) -> list:
    """configure arguments for the Qt6 prebuilt kit (order doesn't matter; values are absolute paths)."""
    args = ["-DCMAKE_TOOLCHAIN_FILE=%s" % qt6_toolchain(env.get("qt_sdk_prefix"))]
    if env.get("qt_host_sdk"):
        args.append("-DQT_HOST_PATH=%s" % env["qt_host_sdk"])
    native = env.get("ohos_sdk_native")
    if native:
        args.append("-DOHOS_SDK_NATIVE=%s" % native)
        chainload = Path(native) / "build" / "cmake" / "ohos.toolchain.cmake"
        args.append("-DQT_CHAINLOAD_TOOLCHAIN_FILE=%s" % chainload)
    args.append("-DOHOS_ARCH=%s" % (env.get("ohos_arch") or "arm64-v8a"))
    make_program = mingw32_make(env)
    if make_program:
        # the kit's own mingw32-make is not on PATH, but CMake needs an absolute path to use it
        args.append("-DCMAKE_MAKE_PROGRAM=%s" % make_program)
    return args


def configure_and_build(state, timeout: float = 1800.0):
    """G3 compile orchestration. Returns the decisive CommandResult."""
    env = env_of(state)
    build_json = state.read_json("build.json", default={}) or {}
    root = Path(state.project_root)
    build_dir = env.get("build_dir", "build-ohos")
    build_abs = Path(native_path(build_dir, root))
    source_abs = Path(native_path(env.get("build_cwd") or ".", root))

    custom = env.get("build_command")
    toolchain = qt6_toolchain(env.get("qt_sdk_prefix"))
    if custom:
        result = state.run_cmd(custom, label="build-custom", timeout=timeout)
        build_json["mode"] = "custom"
    elif toolchain:
        problems = qt6_configure_problems(env)
        if problems:
            # FAIL right away and give the exact config set key: letting cmake report
            # "Could not find a package configuration file" only leads people astray.
            result = state.fail_cmd("compile", "; ".join(problems))
            result.stderr = "\n".join(problems)
            build_json["mode"] = "qt6"
            build_json["qt6_problems"] = problems
            build_json["compile"] = result.to_dict()
            state.write_json("build.json", build_json)
            return result
        cmake = env.get("cmake", "cmake")
        generator = default_generator(env)
        configure = ([cmake, "-S", str(source_abs), "-B", str(build_abs),
                      "-G", generator, "-DCMAKE_BUILD_TYPE=Release"]
                     + qt6_configure_args(env)
                     + _cmake_args(env.get("cmake_args")))
        pkg_extra = pkgconfig_env(state, env)
        result = state.run_cmd(configure, label="cmake-configure",
                               timeout=min(timeout, 900), cwd=root,
                               extra_env=pkg_extra)
        build_json["mode"] = "qt6"
        build_json["generator"] = generator
        build_json["source_dir"] = str(source_abs)
        if result.status == "PASS":
            result = state.run_cmd([cmake, "--build", str(build_abs),
                                    "--parallel"],
                                   label="cmake-build", timeout=timeout,
                                   cwd=root, extra_env=pkg_extra)
    else:
        # Only a prefix, no toolchain: either a Qt5 SDK, or a copied Qt6 tutorial.
        # Both keep the old path (Qt5's qmake/cmake integration really works this way), but record it.
        cmake = env.get("cmake", "cmake")
        cmake_args = _cmake_args(env.get("cmake_args"))
        qt_prefix = env.get("qt_sdk_prefix")
        if qt_prefix:
            cmake_args = cmake_args + ["-DCMAKE_PREFIX_PATH=%s" % qt_prefix]
        generator = default_generator(env)
        configure = ([cmake, "-S", str(source_abs), "-B", str(build_abs),
                      "-DCMAKE_BUILD_TYPE=Release"]
                     + (["-G", generator] if env.get("generator") else [])
                     + cmake_args)
        pkg_extra = pkgconfig_env(state, env)
        result = state.run_cmd(configure, label="cmake-configure",
                               timeout=min(timeout, 600), cwd=root,
                               extra_env=pkg_extra)
        build_json["mode"] = "cmake"
        if result.status == "PASS":
            result = state.run_cmd([cmake, "--build", str(build_abs), "--parallel"],
                                   label="cmake-build", timeout=timeout,
                                   cwd=root, extra_env=pkg_extra)
    build_json["compile"] = result.to_dict()
    if result.status == "PASS":
        build_json["artifacts"] = _find_artifacts(state.project_root, build_dir)
    state.write_json("build.json", build_json)
    return result


VERSIONED_SO_RE = re.compile(r"\.so(\.\d+)+$")
LIBS_ALLOWED_SUFFIX = (".so", ".a")


def _cmake_args(raw) -> list:
    """env.json cmake_args accepts two forms: a JSON array, or a single command-line string.

    The string form is what `config set cmake_args "-G Ninja ..."` naturally produces; the old implementation
    used it as a list directly, `str + list` raised TypeError, turning the most ordinary request -- "switch generator" -- into a crash.
    """
    if not raw:
        return []
    if isinstance(raw, str):
        import shlex
        return shlex.split(raw, posix=(os.name != "nt"))
    return [str(item) for item in raw]


def _sdk_key(value) -> tuple:
    """Normalize "5.0.5(17)" / "5.0.5（17）" / "17" / 17 into (version string, API level)."""
    if value is None:
        return ("", 0)
    text = str(value).strip().replace("（", "(").replace("）", ")")
    api = 0
    match = re.search(r"\((\d+)\)", text)
    if match:
        api = int(match.group(1))
        text = text[:match.start()].strip()
    elif text.isdigit():
        api, text = int(text), ""
    return (text, api)


def _sdk_equal(left, right) -> bool:
    left_key, right_key = _sdk_key(left), _sdk_key(right)
    if not left_key[1] or not right_key[1]:
        return left_key[0] == right_key[0] and left_key[1] == right_key[1]
    # Both have an API level: the API level is a hard constraint; the version strings only need to match when both sides give one
    if left_key[1] != right_key[1]:
        return False
    return not (left_key[0] and right_key[0]) or left_key[0] == right_key[0]


def _package_dirs(state, env: Dict) -> list:
    """Where packaging output lands, by priority: explicit config -> Qt6 deployment dir -> project root.

    The old implementation only looked at `entry/libs` and `build-profile.json5` under the project root, which is the
    Qt5 shell-project layout; Qt6's `_make_hap` / `harmonydeployqt6` output goes to
    `<build_dir>/harmonyos-build/`, so the same checks at the root always "found nothing",
    and preflight was a no-op.
    """
    root = Path(state.project_root)
    candidates = []
    for raw in (env.get("package_dir"), env.get("harmonyos_build")):
        if raw:
            candidates.append((root / raw).resolve())
    candidates.append((root / (env.get("build_dir") or "build-ohos")
                       / "harmonyos-build").resolve())
    candidates.append(root.resolve())
    seen, dirs = set(), []
    for path in candidates:
        if str(path) in seen:
            continue
        seen.add(str(path))
        if path.is_dir():
            dirs.append(path)
    return dirs


def _sdk_from_sdk_home(env: Dict) -> Optional[str]:
    """Read the real version from the SDK install dir (in the form `"6.0.2(22)"`).

    The `compatibleSdkVersion` in the Qt6 template is hard-coded in `src/harmonyos/templates/
    build-profile.json5` (observed as `6.1.0(23)`); when the local SDK is a different version hvigor fails outright with
    `00303082 Unable to find the compatibleSdkVersion ... in SDK Manager`.
    The only reliable source is the SDK's own `oh-uni-package.json`.
    """
    candidates = []
    for key in ("deveco_sdk_home", "deveco_path", "ohos_sdk_native"):
        raw = env.get(key)
        if not raw:
            continue
        base = Path(raw)
        candidates += [base / "default" / "openharmony" / "oh-uni-package.json",
                       base / "oh-uni-package.json",
                       base / ".." / "oh-uni-package.json"]
    for candidate in candidates:
        if not candidate.is_file():
            continue
        try:
            data = json.loads(candidate.read_text(encoding="utf-8",
                                                  errors="replace"))
        except ValueError:
            continue
        version = str(data.get("version") or "").strip()
        api = data.get("apiVersion") or data.get("api_version")
        if version and api:
            # version may have four parts like 6.0.2.1; compatibleSdkVersion uses three
            parts = version.split(".")
            short = ".".join(parts[:3]) if len(parts) >= 3 else version
            return "%s(%s)" % (short, api)
        if api:
            return str(api)
    return None


def _strip_json5(text: str) -> str:
    """Strip JSON5 comments and trailing commas; good enough to read build-profile.json5 / module.json5."""
    out, i, n = [], 0, len(text)
    in_string = False
    while i < n:
        ch = text[i]
        if in_string:
            out.append(ch)
            if ch == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if ch == '"':
                in_string = False
            i += 1
            continue
        if ch == '"':
            in_string = True
            out.append(ch)
            i += 1
            continue
        if text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
            continue
        if text.startswith("/*", i):
            close = text.find("*/", i + 2)
            i = n if close < 0 else close + 2
            continue
        out.append(ch)
        i += 1
    stripped = "".join(out)
    return re.sub(r",(\s*[}\]])", r"\1", stripped)


def read_json5(path) -> Optional[dict]:
    try:
        text = Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    for candidate in (text, _strip_json5(text)):
        try:
            data = json.loads(candidate)
        except ValueError:
            continue
        if isinstance(data, dict):
            return data
    return None


def align_sdk_profile(state, env: Dict) -> list:
    """Align compatibleSdkVersion in the packaging dir's `build-profile.json5` with the real SDK.

    Returns human-readable change descriptions (empty list = nothing changed). This is the **only** place that should change this field:
    iron rule B4 forbids setting compileSdkVersion / targetSdkVersion in sources/templates, while
    compatibleSdkVersion must equal the version actually installed in the SDK, otherwise hvigor reports 00303082.
    """
    wanted = env.get("compatible_sdk") or _sdk_from_sdk_home(env)
    if not wanted:
        return []
    changes = []
    for directory in _package_dirs(state, env):
        profile = directory / "build-profile.json5"
        if not profile.is_file():
            continue
        text = profile.read_text(encoding="utf-8", errors="replace")
        match = re.search(r'("compatibleSdkVersion"\s*:\s*)'
                          r'(?:"([^"]*)"|(\d+))', text)
        if not match:
            continue
        current = match.group(2) or match.group(3)
        if _sdk_equal(current, wanted):
            continue
        replacement = '%s"%s"' % (match.group(1), wanted)
        profile.write_text(text[:match.start()] + replacement + text[match.end():],
                           encoding="utf-8")
        changes.append("%s: compatibleSdkVersion %s -> %s"
                       % (profile.as_posix(), current, wanted))
    return changes


def _sdk_problems(state, env: Dict) -> list:
    """Give an actionable fix when compatibleSdkVersion does not match the SDK version."""
    want = _sdk_from_sdk_home(env)
    declared = None
    for directory in _package_dirs(state, env):
        profile = directory / "build-profile.json5"
        if not profile.is_file():
            continue
        match = re.search(r'"compatibleSdkVersion"\s*:\s*'
                          r'(?:"([^"]+)"|(\d+))',
                          profile.read_text(encoding="utf-8", errors="replace"))
        if match:
            declared = match.group(1) or match.group(2)
            break
    if want and declared and not _sdk_equal(declared, want):
        return ["build-profile.json5 compatibleSdkVersion=%s does not match the local SDK=%s"
                " (hvigor will report 00303082); this tool aligns it automatically, "
                "or use `qt-ohos-run config set compatible_sdk %s`"
                % (declared, want, want)]
    return []


def preflight_package(state):
    """Pre-packaging check of libs placement, non-.so files, and compatibleSdkVersion vs the SDK version.

    1. **Versioned .so**: `libfoo.so.1` placed in `entry/libs/<abi>/` is packed into the HAP as-is,
          but the loader looks up `libfoo.so` by soname, so dlopen fails after install.
    2. **Non-.so files**: hvigor only copies `.so` (`.a` static libs don't go into the package); other suffixes are silently ignored,
          showing up as "but I did put libruntime.so.1.2 in there".
    3. **compatibleSdkVersion**: hvigor refuses to package when it doesn't match the actual SDK version.

    Returns (errors, warnings), both human-readable strings.
    """
    env = env_of(state)
    errors, warns = [], []
    dirs = _package_dirs(state, env)
    if not dirs:
        warns.append("packaging dir not found (tried package_dir / <build_dir>/harmonyos-build / "
                     "project root) -- skipping libs and SDK version checks")

    for directory in dirs:
        for arch_dir in sorted(directory.glob("**/entry/libs/*")):
            if not arch_dir.is_dir():
                continue
            for path in sorted(arch_dir.iterdir()):
                if not path.is_file():
                    continue
                if VERSIONED_SO_RE.search(path.name):
                    plain = path.name.split(".so")[0] + ".so"
                    if (arch_dir / plain).exists():
                        continue      # soname satisfied by a same-name copy, not an error
                    errors.append(
                        "%s is a versioned .so: the loader can't find it by soname; "
                        "rename it to .so (or also provide a same-name copy %s)"
                        % (path.as_posix(), plain))
                elif not path.name.endswith(LIBS_ALLOWED_SUFFIX):
                    warns.append("%s is not a .so and will be ignored during packaging"
                                 % path.as_posix())

    declared = None
    for directory in dirs:
        profile = directory / "build-profile.json5"
        if not profile.is_file():
            continue
        match = re.search(r'"compatibleSdkVersion"\s*:\s*'
                          r'(?:"([^"]+)"|(\d+))',
                          profile.read_text(encoding="utf-8", errors="replace"))
        if match:
            declared = match.group(1) or match.group(2)
            if '"runtimeOS"' in profile.read_text(encoding="utf-8",
                                                  errors="replace"):
                runtime_os = re.search(r'"runtimeOS"\s*:\s*"([^"]+)"',
                                       profile.read_text(encoding="utf-8",
                                                         errors="replace"))
                if runtime_os and runtime_os.group(1) != "HarmonyOS":
                    warns.append("%s runtimeOS=%s (Qt apps need HarmonyOS)"
                                 % (profile.as_posix(), runtime_os.group(1)))
            break

    wanted = env.get("compatible_sdk")
    if wanted and declared and not _sdk_equal(wanted, declared):
        errors.append(
            "build-profile.json5 compatibleSdkVersion=%s does not match env.json "
            "compatible_sdk=%s (install may be rejected, or APIs the device lacks may be used)"
            % (declared, wanted))
    else:
        errors.extend(_sdk_problems(state, env))

    return errors, warns


def find_hvigor(env: Dict) -> Optional[str]:
    """Locate hvigorw. Without it hvigor just prints a warning and **returns 0** -- a classic false success."""
    raw = env.get("hvigor")
    candidates = []
    if raw:
        candidates.append(Path(raw))
    for key in ("deveco_path", "deveco_studio", "deveco_sdk_home"):
        base = env.get(key)
        if base:
            candidates.append(Path(base) / "tools" / "hvigor" / "bin"
                              / ("hvigorw.bat" if os.name == "nt" else "hvigorw"))
    for candidate in candidates:
        if candidate.is_file():
            return str(candidate.resolve())
    for name in ("hvigorw.bat", "hvigorw"):
        found = shutil.which(name)
        if found:
            return found
    return None


def hvigor_env(state, env: Dict, create: bool = True) -> Dict:
    """The five things hvigor needs to run; missing any one blows up at the signing/build stage.

    1. `QT_HARMONYOS_HVIGOR`: absolute path; without it `_make_hap` only prints
          "No hvigor path specified, skipping build" and **returns 0**.
    2. `JAVA_HOME`: DevEco's bundled jbr.
    3. `DEVECO_SDK_HOME`: the CLI's sdk root.
    4. `HVIGOR_USER_HOME`: must be an absolute writable path, otherwise EPERM mkdir;
          a relative path is silently ignored (with the hint Invalid custom userhome hvigor data dir).
    5. `npm_config_cache`: must be on a writable disk, otherwise npm EPERM.
    """
    extra: Dict[str, str] = {}
    root = Path(state.project_root)
    hvigor = find_hvigor(env)
    if hvigor:
        extra["QT_HARMONYOS_HVIGOR"] = hvigor
    java_home = env.get("java_home")
    if not java_home:
        for key in ("deveco_path", "deveco_studio"):
            base = env.get(key)
            if base and (Path(base) / "jbr").is_dir():
                java_home = str(Path(base) / "jbr")
                break
    if java_home:
        extra["JAVA_HOME"] = str(Path(java_home).resolve())
    sdk_home = env.get("deveco_sdk_home") or env.get("deveco_path")
    if sdk_home:
        candidate = Path(sdk_home)
        if (candidate / "sdk").is_dir():
            candidate = candidate / "sdk"
        extra["DEVECO_SDK_HOME"] = str(candidate.resolve())
    hvigor_home = env.get("hvigor_home") or (root / ".qt-ohos" / "hvigor-home")
    npm_cache = env.get("npm_cache") or (root / ".qt-ohos" / "npm-cache")
    if create:
        # Only create dirs when packaging/installing; read-only checks like doctor shouldn't create things in someone else's project.
        Path(hvigor_home).mkdir(parents=True, exist_ok=True)
        Path(npm_cache).mkdir(parents=True, exist_ok=True)
    extra["HVIGOR_USER_HOME"] = str(Path(hvigor_home).resolve())
    extra["npm_config_cache"] = str(Path(npm_cache).resolve())
    return extra


