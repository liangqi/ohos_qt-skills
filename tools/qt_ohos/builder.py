def deployment_settings(state, env: Dict) -> list:
    """Qt6's `_make_hap` depends on `<target>-harmony-deployment-settings.json`."""
    root = Path(state.project_root)
    build_dir = (root / (env.get("build_dir") or "build-ohos")).resolve()
    found = sorted(build_dir.glob("**/*-harmony-deployment-settings.json"))
    return [p for p in found if "/.qt-ohos/" not in p.as_posix()]


def auto_package(state, env: Dict, timeout: float):
    """The two built-in Qt6 packaging paths; when neither is available, explicitly SKIP instead of pretending it ran.

    Path 1: `cmake --build <bld> --target <target>_make_hap`
                  (the one-shot target defined in `Qt6HarmonyOSMacros.cmake:663-667`)
    Path 2: `harmonydeployqt6 --input <settings> --output <dir> --hvigor <abs>`
    A user-supplied `package_command` still has top priority (see `package_hap`).
    """
    root = Path(state.project_root)
    build_dir = (root / (env.get("build_dir") or "build-ohos")).resolve()
    settings = deployment_settings(state, env)
    target = env.get("package_target")
    if not target and settings:
        stem = settings[0].name[:-len("-harmony-deployment-settings.json")]
        target = stem + "_make_hap"
    extra = hvigor_env(state, env)
    notes = []
    if "QT_HARMONYOS_HVIGOR" not in extra:
        notes.append("hvigorw not found (when missing it prints No hvigor path specified and "
                     "returns 0): config set hvigor <absolute path>/hvigorw.bat")

    if target and shutil.which("cmake"):
        result = state.run_cmd([env.get("cmake", "cmake"), "--build",
                                str(build_dir), "--target", target],
                               label="package-make-hap", timeout=timeout,
                               cwd=root, extra_env=extra)
        if result.status == "PASS":
            result.stderr += ("\n[qt-ohos-run] false-success guard: hvigor was not invoked"
                              if re.search(r"No hvigor path specified",
                                           result.stdout + result.stderr)
                              else "")
            if "No hvigor path specified" in (result.stdout + result.stderr):
                result.status = "FAIL"
        fixes = hvigor_diagnostics(result.stdout + "\n" + result.stderr)
        if fixes:
            notes.extend(fixes)
            if result.status == "PASS":
                result.status = "FAIL"
    else:
        hdq = None
        for name in ("harmonydeployqt6", "harmonydeployqt6.exe"):
            candidate = shutil.which(name)
            if candidate:
                hdq = candidate
                break
            if env.get("qt_host_sdk"):
                path = Path(env["qt_host_sdk"]) / "bin" / name
                if path.is_file():
                    hdq = str(path)
                    break
        if hdq and settings:
            out_dir = (root / (env.get("harmonyos_build") or "")
                       ) if env.get("harmonyos_build") else build_dir / "harmonyos-build"
            args = [hdq, "--input", str(settings[0]), "--output", str(out_dir)]
            if "QT_HARMONYOS_HVIGOR" in extra:
                args += ["--hvigor", extra["QT_HARMONYOS_HVIGOR"]]
            result = state.run_cmd(args, label="harmonydeployqt6", timeout=timeout,
                                   cwd=root, extra_env=extra)
            fixes = hvigor_diagnostics(result.stdout + "\n" + result.stderr)
            if fixes:
                notes.extend(fixes)
                if result.status == "PASS":
                    result.status = "FAIL"
        else:
            reason = ("there is neither <target>-harmony-deployment-settings.json nor "
                      "harmonydeployqt6: first get `build` to succeed once (Qt6's deployment file is generated from the build "
                      "output), or use `package --record-only --hap <file>` to register "
                      "an externally packaged result")
            if notes:
                reason += "; " + "; ".join(notes)
            result = state.skip_cmd("package", reason)
    if notes:
        result.stderr = (result.stderr + "\n[qt-ohos-run] " + "\n[qt-ohos-run] ".join(notes)).strip()
    return result


def package_hap(state, timeout: float = 1800.0):
    env = env_of(state)
    build_json = state.read_json("build.json", default={}) or {}
    aligned = align_sdk_profile(state, env)
    errors, warns = preflight_package(state)
    build_json["package_preflight"] = {"errors": errors, "warnings": warns,
                                       "sdk_aligned": aligned}
    if errors:
        # These errors, if found only after packaging, can only be guessed at on the device; stop them early with an actionable fix.
        # The record must be FAIL: recording SKIP would make `status` disagree with the gates (SKIP means "not tested",
        # while here it is explicitly "tested, not acceptable").
        result = state.fail_cmd("package", "; ".join(errors))
        result.stderr = "\n".join(errors)
        build_json["package"] = result.to_dict()
        state.write_json("build.json", build_json)
        return result
    command = env.get("package_command")
    if command:
        result = state.run_cmd(command, label="package-hap", timeout=timeout,
                               cwd=env.get("package_dir") or None,
                               extra_env=hvigor_env(state, env))
        fixes = hvigor_diagnostics(result.stdout + "\n" + result.stderr)
        if fixes:
            result.stderr += "\n[qt-ohos-run] " + "\n[qt-ohos-run] ".join(fixes)
            if result.status == "PASS":
                result.status = "FAIL"
    else:
        result = auto_package(state, env, timeout)
    build_json["package"] = result.to_dict()
    if result.status == "PASS":
        hap = find_hap(state.project_root, env.get("hap_glob"))
        build_json["hap"] = hap
        if not hap:
            result.status = "FAIL"
            result.stderr += "\n[qt-ohos-run] build succeeded but no .hap found"
            build_json["package"] = result.to_dict()
        else:
            # Record a fingerprint: from now on the G6-G9 PASS is bound to "this HAP, this device";
            # after repackaging, old records are judged STALE instead of continuing to pass as PASS.
            try:
                hap_path = Path(hap)
                if not hap_path.is_absolute():
                    hap_path = Path(state.project_root) / hap
                stat = hap_path.stat()
                build_json["hap_fingerprint"] = {
                    "sha256": file_sha256(hap_path),
                    "size": stat.st_size,
                    "mtime_ns": stat.st_mtime_ns,
                }
            except OSError:
                pass
            ability = detect_ability(state, env)
            if ability and not env.get("ability_name"):
                env["ability_name"] = ability
                state.data.setdefault("env", {}).update(env)
                state.save()
    state.write_json("build.json", build_json)
    return result


def find_hap(project_root, hap_glob: Optional[str] = None) -> Optional[str]:
    """Find the HAP output: signed takes priority, and **only files that really exist count**.

    Two pitfalls seen in practice: (1) when `signed/` and `unsigned/` outputs with the same name coexist, the order of `sorted(glob)`
    makes install randomly pick unsigned (which won't install); (2) after the output is deleted by hand, the old path
    stays in build.json, and install keeps failing with no visible reason.
    """
    root = Path(project_root)
    patterns = hap_glob.split(",") if hap_glob else [
        "**/build/**/*.hap", "**/*.hap"]
    found = []
    for pattern in patterns:
        for path in sorted(globmod.glob(str(root / pattern), recursive=True)):
            if "/.qt-ohos/" in path.replace("\\", "/"):
                continue
            if not Path(path).is_file() or Path(path).stat().st_size == 0:
                continue
            found.append(path)
    if not found:
        return None
    found.sort(key=lambda item: (0 if "-signed" in Path(item).name else 1,
                                 Path(item).as_posix()))
    return str(Path(found[0]).relative_to(root).as_posix())


def detect_ability(state, env: Dict) -> Optional[str]:
    """Read mainElement/abilities from module.json5, instead of a hard-coded `EntryAbility`.

    The Qt6 template's ability is called `QAbility` (`entry/src/main/ets/qability/QAbility.ets`),
    while the Qt5 shell project calls it `EntryAbility`. When the default guess is wrong `aa start` reports
    "ability not found", which looks like the app failed to start.
    """
    root = Path(state.project_root)
    modules = []
    for base in _package_dirs(state, env) or [root]:
        modules += sorted(base.glob("**/module.json5"))
    modules = [m for m in modules if "/.qt-ohos/" not in m.as_posix()]
    for path in modules:
        data = read_json5(path)
        if not isinstance(data, dict):
            continue
        module = data.get("module") if isinstance(data.get("module"), dict) else data
        abilities = module.get("abilities") or []
        names = [a.get("name") for a in abilities if isinstance(a, dict) and a.get("name")]
        main = module.get("mainElement")
        if main and main in names:
            return main
        if names:
            return names[0]
    return None


_FAULTLOG_DIR = "/data/log/faultlog/faultlogger"
# OHOS system-side crash lines (processdump / DfxFaultLogger) carry no bundle name;
# filtering by bundle drops real crashes entirely -- this is the direct cause of D-01.
_SYSTEM_CRASH_TOKENS = ("processdump", "dfxfaultlogger", "reason:signal",
                        "fault thread info", "process died", "dlopen failed",
                        "appfreeze", "cppcrash", "jscrash")


def file_sha256(path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def device_serial(env: Dict) -> Optional[str]:
    """Serial of the first online device; None if unavailable (no conclusion is drawn from it)."""
    hdc = env.get("hdc") or find_hdc()
    try:
        completed = subprocess.run([hdc, "list", "targets"],
                                   capture_output=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    text = completed.stdout.decode("utf-8", "replace")
    for line in text.splitlines():
        line = line.strip()
        if line and "empty" not in line.lower():
            return line.split()[0]
    return None


def _faultlog_names(state, hdc: str) -> Optional[set]:
    """Set of file names in the faultlogger directory; None if unreadable (not an empty set)."""
    result = state.run_cmd([hdc, "shell", "ls", _FAULTLOG_DIR],
                           label="faultlogger-list", timeout=40)
    text = (result.stdout or "") + "\n" + (result.stderr or "")
    names = {line.strip().rsplit("/", 1)[-1] for line in text.splitlines()
             if line.strip().endswith(".log")}
    if names:
        return names
    if result.exit_code == 0 and "No such file" not in text:
        return set()
    return None


def _process_alive(state, hdc: str, process: str) -> str:
    """"alive" / "gone" / "unknown": whether the process is still there when the window ends."""
    if not process:
        return "unknown"
    result = state.run_cmd([hdc, "shell", "pidof", process],
                           label="pidof", timeout=40)
    text = ((result.stdout or "") + " " + (result.stderr or "")).strip()
    first = text.split()[0] if text.split() else ""
    if first.isdigit():
        return "alive"
    lowered = text.lower()
    if any(token in lowered for token in ("not found", "error", "failed",
                                          "no such", "unknown")):
        return "unknown"
    return "gone" if not first else "unknown"


def _stamp_runtime(record: Dict, state, env: Dict, build_json: Dict) -> None:
    """Write "which HAP and which device this record belongs to" into runtime.json."""
    record["device_serial"] = device_serial(env)
    fingerprint = build_json.get("hap_fingerprint") or {}
    sha = fingerprint.get("sha256")
    if not sha:
        hap = build_json.get("hap")
        if hap:
            path = Path(hap)
            if not path.is_absolute():
                path = Path(state.project_root) / hap
            if path.is_file():
                sha = file_sha256(path)
    if sha:
        record["hap_sha256"] = sha


def install_hap(state, timeout: float = 300.0):
    env = env_of(state)
    runtime = state.read_json("runtime.json", default={}) or {}
    build_json = state.read_json("build.json", default={}) or {}
    root = Path(state.project_root)
    hap = build_json.get("hap")
    hdc = env.get("hdc") or find_hdc()
    if not hap:
        result = state.skip_cmd("install", "no HAP artifact recorded")
    else:
        path = Path(hap)
        if not path.is_absolute():
            path = root / hap
        if not path.is_file():
            # The cached path may have been deleted: look again, then decide on FAIL
            fresh = find_hap(root, env.get("hap_glob"))
            if fresh:
                path = root / fresh
                build_json["hap"] = fresh
                state.write_json("build.json", build_json)
        if not path.is_file():
            result = state.fail_cmd(
                "install", "HAP does not exist: %s (re-run package, or package --record-only --hap)"
                % path)
        else:
            # hdc on Windows doesn't accept POSIX relative paths; the error it reports is
            # "Error opening file: no such file or directory, path:C:\...\C:/Users/..."
            result = state.run_cmd([hdc, "install", "-r", native_path(path)],
                                   label="hdc-install", timeout=timeout)
            if result.status == "PASS" and "fail" in (
                    result.stdout + result.stderr).lower():
                result.status = "FAIL"
    runtime["install"] = result.to_dict()
    if result.status == "PASS":
        _stamp_runtime(runtime["install"], state, env, build_json)
    state.write_json("runtime.json", runtime)
    return result


def launch_app(state, timeout: float = 120.0):
    env = env_of(state)
    runtime = state.read_json("runtime.json", default={}) or {}
    build_json = state.read_json("build.json", default={}) or {}
    hdc = env.get("hdc") or find_hdc()
    bundle = env.get("bundle_name")
    ability = env.get("ability_name") or detect_ability(state, env)
    if not bundle:
        result = state.skip_cmd("launch", "env.json: bundle_name not set")
    elif not ability:
        result = state.fail_cmd(
            "launch",
            "ability name not found: env.json has no ability_name, and the packaging dir has no parsable "
            "module.json5 (the Qt6 template uses QAbility, Qt5 uses EntryAbility)")
    else:
        result = state.run_cmd(
            [hdc, "shell", "aa", "start", "-b", bundle, "-a", ability],
            label="aa-start", timeout=timeout)
        combined = (result.stdout + result.stderr).lower()
        if result.status == "PASS" and ("error" in combined or "fail" in combined):
            result.status = "FAIL"
            result.stderr += ("\n[qt-ohos-run] ability used=%s; if it reports ability not found, "
                              "check with `aa dump -a` or module.json5, then "
                              "`config set ability_name <name>`" % ability)
    runtime["launch"] = result.to_dict()
    if result.status == "PASS":
        _stamp_runtime(runtime["launch"], state, env, build_json)
    state.write_json("runtime.json", runtime)
    return result


def crash_check(state, timeout: Optional[float] = None):
    """Capture a device log window after launch and decide whether we crashed.

    Three independent pieces of evidence; missing any one turns "didn't run" or "crashed but logs were filtered out" into "no crash"
    (the cause of D-01):

    1. **Process liveness at the end of the window**: empty `pidof` means the process vanished during the observation window;
    2. **New faultlogger files**: only the difference before/after the window start is considered; file names look like
          `cppcrash-<bundle>-<uid>-<YYYYMMDDHHMMSSmmm>.log`; ls time formats are not parsed,
          nor does it depend on host and device sharing a time zone;
    3. **Union of crash lines**: this app's log lines ∪ system crash lines (`processdump` /
          `DfxFaultLogger`). System crash lines carry no bundle name, so filtering only by bundle would drop them
          entirely; they are fetched separately, keeping only lines that mention this app's symbols/process.

    Still SKIP when upstream install/launch is not PASS: without a "running app", a crash window
    is meaningless. If none of the three pieces of evidence can be obtained -> NOT_RUN; never PASS on empty evidence.
    """
    env = env_of(state)
    runtime = state.read_json("runtime.json", default={}) or {}
    build_json = state.read_json("build.json", default={}) or {}
    bundle = env.get("bundle_name")

    for step in ("install", "launch"):
        status = str((runtime.get(step) or {}).get("status", "NOT_RUN"))
        if status != "PASS":
            result = state.skip_cmd(
                "crash_check",
                "upstream %s is %s - crash window is meaningless without a "
                "running app" % (step, status))
            result.stderr = "SKIP: upstream %s=%s; not a PASS" % (step, status)
            runtime["crash_check"] = result.to_dict()
            runtime["crash_markers_found"] = []
            state.write_json("runtime.json", runtime)
            return result

    hdc = env.get("hdc") or find_hdc()
    wait_sec = float(env.get("crash_wait_sec", 8))
    timeout = timeout or (wait_sec + 90)
    process = env.get("process_name") or (bundle.rsplit(".", 1)[-1] if bundle else "")
    terms = [t for t in {bundle or "", process} if t]

    # Pre-snapshot for evidence 2: a crash log may belong to this app or to another process;
    # only "new within the window + name belongs to this app" counts.
    before = _faultlog_names(state, hdc)

    result = state.run_cmd([hdc, "shell", "timeout", str(int(wait_sec)),
                            "hilog"], label="hilog-crash-window",
                           timeout=timeout)
    raw = (result.stdout or "") + "\n" + (result.stderr or "")
    lines = raw.splitlines()
    scoped = ([ln for ln in lines if any(t.lower() in ln.lower() for t in terms)]
              if terms else lines)
    if terms and not scoped and bundle:
        wide = [seg for seg in bundle.split(".") if len(seg) >= 4]
        wide_scoped = [ln for ln in lines
                       if any(t.lower() in ln.lower() for t in wide)]
        if wide_scoped:
            terms, scoped = wide, wide_scoped

    # Evidence 3: system crash lines. Include the artifact name, otherwise lines like "libtd_app.so(main+5616)"
    # with only a library name and no process name would be taken as "another app".
    ours = [name for name in terms if name]
    for item in build_json.get("artifacts") or []:
        raw_path = item.get("path") if isinstance(item, dict) else str(item)
        if raw_path:
            ours.append(Path(raw_path).name)
    system_lines = [ln for ln in lines
                    if any(token in ln.lower() for token in _SYSTEM_CRASH_TOKENS)]
    system_ours = [ln for ln in system_lines
                   if any(tag.lower() in ln.lower() for tag in ours if tag)]

    app_markers = ["cppcrash", "jscrash", "appfreeze", "sigsegv", "sigabrt",
                   "faultlog", "process died", "dlopen failed"]
    found = [m for m in app_markers
             if m in "\n".join(scoped).lower() or m in "\n".join(system_ours).lower()]

    time.sleep(1.0)
    after = _faultlog_names(state, hdc)
    new_logs = []
    if before is not None and after is not None:
        new_logs = sorted(name for name in (after - before)
                          if any(tag.lower() in name.lower() for tag in terms if tag))
    pid_state = _process_alive(state, hdc, process)

    evidence = {
        "app_lines": len(scoped),
        "system_crash_lines": len(system_lines),
        "system_crash_lines_ours": len(system_ours),
        "faultlogger_new": new_logs[:5],
        "faultlogger_available": before is not None and after is not None,
        "pid": pid_state,
        "pid_name": process,
        "filtered_by": terms,
        "window_sec": int(wait_sec),
    }
    result.exit_code = 0  # hilog capture exit code is not a verdict

    reasons: List[str] = []
    if found:
        reasons.append("crash markers: %s" % ", ".join(sorted(set(found))))
    if system_ours:
        reasons.append("system crash line: %s" % system_ours[0].strip()[:120])
    if new_logs:
        reasons.append("new faultlogger files: %s" % ", ".join(new_logs[:3]))
    if pid_state == "gone":
        reasons.append("pidof %s empty at end of window" % (process or "<process>"))

    if reasons:
        result.status = "FAIL"
        result.stderr = " | ".join(reasons)
    elif result.status != "PASS":
        result.stderr = "crash window capture failed: %s" % result.stderr.strip()[:200]
    elif terms and not scoped and pid_state != "alive":
        result.status = "NOT_RUN"
        result.stderr = ("no log line matched %s in %ss window and the process "
                         "is not alive at window end - inconclusive, not a PASS"
                         % ("/".join(terms), int(wait_sec)))
    else:
        result.stderr = ("no crash evidence in %ss window: %d app line(s), "
                         "%d system line(s), faultlogger +%d, pid=%s%s" % (
                             int(wait_sec), len(scoped), len(system_lines),
                             len(new_logs), pid_state,
                             ", filtered by %s" % "/".join(terms) if terms
                             else ", unfiltered"))

    runtime["crash_check"] = result.to_dict()
    runtime["crash_check"]["bundle_filtered"] = bool(terms)
    runtime["crash_check"]["crash_evidence"] = evidence
    runtime["crash_markers_found"] = sorted(set(found))
    state.write_json("runtime.json", runtime)
    return result


def check_ui_window(state, timeout: float = 60.0):
    """G9 evidence: dump the layout tree of the launched bundle via uitest.

    Writes runtime['ui_window_seen'] (True/False). A successful dump means the
    app window exists; failures fall back to PARTIAL + manual `mark-ui`.
    """
    env = env_of(state)
    runtime = state.read_json("runtime.json", default={}) or {}
    hdc = env.get("hdc", "hdc")
    bundle = env.get("bundle_name")
    if not bundle:
        result = state.skip_cmd("ui_window", "env.json: bundle_name not set")
    else:
        result = state.run_cmd(
            [hdc, "shell", "uitest", "dumpLayout", "-b", bundle],
            label="uitest-dump-layout", timeout=timeout)
        combined = (result.stdout + "\n" + result.stderr).lower()
        if result.status == "PASS" and ("error" in combined or "fail" in combined):
            result.status = "FAIL"
            result.stderr += "\n[qt-ohos-run] uitest dumpLayout reported failure"
    runtime["ui_window"] = result.to_dict()
    runtime["ui_window_seen"] = (result.status == "PASS")
    state.write_json("runtime.json", runtime)
    return result


def _find_artifacts(project_root, build_dir: str):
    root = Path(project_root)
    artifacts = []
    search_dir = root / build_dir
    dirs = [search_dir] if search_dir.is_dir() else [root]
    for base in dirs:
        for pattern in ("**/*.so",):
            for path in globmod.glob(str(base / pattern), recursive=True):
                rel = Path(path).relative_to(root).as_posix()
                if ".qt-ohos" not in rel:
                    artifacts.append(rel)
        if artifacts:
            break
    return artifacts[:50]


